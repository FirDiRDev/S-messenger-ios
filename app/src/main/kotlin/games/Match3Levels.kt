    /** Ходы сгенерированного уровня (null - нарисованный). */
    fun generatedMoves(level: Int): Int? = when {
        spec(level) != null -> null
        level in 1..LEGACY_MOVES.size -> LEGACY_MOVES[level - 1]
        else -> 33 + level % 4
    }

    /** Пороги звёзд сгенерированного уровня. */
    fun generatedStars(level: Int): IntArray {
        if (level in 1..LEGACY_STARS.size / 3) return LEGACY_STARS.copyOfRange((level - 1) * 3, level * 3)
        val s2 = 26000 + (level - LAST).coerceIn(0, 200) * 60
        return intArrayOf(s2 / 2, s2, s2 * 3 / 2)
    }

    /** Последний нарисованный уровень (дальше - снова генерируются). */
    val LAST: Int get() = FIRST + RAW.size - 1

    val count: Int get() = RAW.size

    /** Описание нарисованного уровня или null (уровень генерируется). */
    fun spec(level: Int): Spec? {
        val r = RAW.getOrNull(level - FIRST) ?: return null
        val colors = ArrayList<Pair<Int, Int>>()
        var score = 0
        for (tok in r.goals.split(' ')) {
            if (tok.isBlank()) continue
            val (k, v) = tok.split(':')
            if (k == "s") score = v.toInt() else colors += k.drop(1).toInt() to v.toInt()
        }
        return Spec(r.map, r.moves, r.kinds, colors, score, r.stars)
    }
