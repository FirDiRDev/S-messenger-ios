package com.stoyko.smessenger

/**
 * Простое шифрование строк (замена плагину StringFog, который не работает с Android Gradle
 * Plugin 9). Чувствительные константы (адреса серверов обновлений, адрес помощника) хранятся
 * в коде не текстом, а зашифрованными байтами - в дампе строк готового APK их не видно, а R8
 * не может «собрать» их обратно. Расшифровка - в рантайме, по требованию.
 *
 * Шифр: байт XOR с ключом (по кругу) XOR с предыдущим зашифрованным байтом (сцепление - один
 * и тот же символ даёт разные байты). Это не стойкая криптография, а защита от беглого чтения
 * декомпилятором; настоящие секреты (ключ подписи, пароли) здесь не хранятся.
 *
 * Литералы и этот ключ генерируются скриптом (tools/strenc.py) - менять их вручную не нужно.
 */
object Obf {
    private val KEY = byteArrayOf(83, 109, 46, 55, -87, 28, -12, -128)

    fun d(enc: ByteArray): String {
        val out = ByteArray(enc.size)
        var prev = 0x5A
        for (i in enc.indices) {
            val x = enc[i].toInt() and 0xFF
            out[i] = (x xor (KEY[i % KEY.size].toInt() and 0xFF) xor prev).toByte()
            prev = x
        }
        return String(out, Charsets.UTF_8)
    }

    /** 'FirDiRDev/S-messenger' */
